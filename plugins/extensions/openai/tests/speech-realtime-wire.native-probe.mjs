function assertUpgrade(peer, pathname, apiKey) {
  assert.equal(peer.request.method, 'GET');
  assert.equal(peer.request.headers.upgrade, 'websocket');
  assert.equal(peer.request.url, pathname);
  assert.equal(peer.request.headers.authorization, apiKey ? `Bearer ${apiKey}` : undefined);
  const allowedHeaders = new Set([
    'host',
    'upgrade',
    'connection',
    'sec-websocket-key',
    'sec-websocket-version',
    'sec-websocket-extensions',
    'authorization',
    'openai-beta',
    'user-agent',
    'origin',
  ]);
  assert.deepEqual(
    Object.keys(peer.request.headers).filter(name => !allowedHeaders.has(name)),
    [],
  );
}

async function transcriptionWire() {
  const { createRealtimeTranscriptionWebSocketSession } = await native(
    'realtime-transcription-session',
  );
  const { resolveProviderRequestHeaders } = await native('provider-http');
  const provider = implementation.buildOpenAIRealtimeTranscriptionProvider({
    createRealtimeTranscriptionWebSocketSession,
    resolveProviderRequestHeaders,
  });
  const profile = (baseUrl, apiKey) => ({
    protocolId: 'openai-transcription-realtime',
    baseUrl,
    model: 'office/asr-arbitrary-v3',
    language: 'zh',
    prompt: 'Fixture vocabulary',
    apiKey,
  });
  const create = (service, apiKey, events) => {
    const cfg = {
      plugins: {
        entries: { openai: { config: { transcription: profile(service.baseUrl, apiKey) } } },
      },
    };
    const providerConfig = provider.resolveConfig({ cfg, rawConfig: {} });
    return provider.createSession({
      cfg,
      providerConfig,
      onPartial: text => events.push({ kind: 'partial', text }),
      onTranscript: text => events.push({ kind: 'final', text }),
      onSpeechStart: () => events.push({ kind: 'speech-start' }),
      onError: error => events.push({ kind: 'error', message: error.message }),
    });
  };
  const acknowledge = (peer, frame) => {
    if (frame.type === 'session.update') void peer.send({ type: 'session.updated' });
  };
  const checkUpdate = async peer => {
    const update = await peer.frames.wait(event => event.type === 'session.update');
    assert.deepEqual(update, {
      type: 'session.update',
      session: {
        type: 'transcription',
        audio: {
          input: {
            format: { type: 'audio/pcmu' },
            transcription: {
              model: 'office/asr-arbitrary-v3',
              language: 'zh',
              prompt: 'Fixture vocabulary',
            },
            turn_detection: {
              type: 'server_vad',
              threshold: 0.5,
              prefix_padding_ms: 300,
              silence_duration_ms: 800,
            },
          },
        },
      },
    });
  };
  const service = await fakeService((peer, frame) => {
    acknowledge(peer, frame);
    if (frame.type === 'input_audio_buffer.commit') {
      void peer.send({
        type: 'input_audio_buffer.committed',
        item_id: 'second',
        previous_item_id: 'first',
      });
      void peer.send({
        type: 'conversation.item.input_audio_transcription.completed',
        item_id: 'second',
        transcript: 'Stopped final',
      });
      peer.socket.close(1000, 'final delivered');
    }
  });
  const events = channel('transcription callback');
  const session = create(service, 'wire-asr-key', events);
  try {
    assert.equal(provider.defaultModel, undefined);
    for (const fields of [
      { model: undefined },
      { model: '' },
      { baseUrl: undefined },
      { model: '\ncustom-model' },
      { baseUrl: `${service.baseUrl}/audio/speech` },
      { baseUrl: `${service.baseUrl}/realtime?token=invalid` },
    ]) {
      const invalid = { ...profile(service.baseUrl, ''), ...fields };
      assert.equal(provider.isConfigured({ providerConfig: invalid }), false);
      assert.throws(() => provider.createSession({ providerConfig: invalid }));
    }
    assert.equal(service.peers.values.length, 0, 'missing settings must not open a socket');
    const queued = Buffer.from([0, 127, 128, 255]);
    session.sendAudio(queued);
    await session.connect();
    const peer = await service.peers.wait();
    assertUpgrade(peer, '/deployment/audio/realtime?intent=transcription', 'wire-asr-key');
    await checkUpdate(peer);
    assert.equal(session.isConnected(), true);
    const firstAudio = await peer.frames.wait(event => event.type === 'input_audio_buffer.append');
    assert.deepEqual(Buffer.from(firstAudio.audio, 'base64'), queued);
    await peer.send({ type: 'input_audio_buffer.speech_started', item_id: 'first' });
    await peer.send({
      type: 'input_audio_buffer.committed',
      item_id: 'first',
      previous_item_id: null,
    });
    await peer.send({
      type: 'conversation.item.input_audio_transcription.delta',
      item_id: 'first',
      delta: '本机 ',
    });
    await peer.send({
      type: 'conversation.item.input_audio_transcription.delta',
      item_id: 'first',
      delta: '转写',
    });
    await peer.send({
      type: 'conversation.item.input_audio_transcription.completed',
      item_id: 'first',
      transcript: '本机 转写',
    });
    await events.wait(event => event.kind === 'final');
    await peer.send({
      type: 'conversation.item.input_audio_transcription.completed',
      item_id: 'first',
      transcript: 'Duplicate final',
    });
    await peer.send({ type: 'input_audio_buffer.speech_started', item_id: 'second' });
    await events.wait(
      event =>
        event.kind === 'speech-start' &&
        events.values.filter(value => value.kind === 'speech-start').length === 2,
    );
    assert.deepEqual(
      events.values.filter(event => event.kind === 'partial').map(event => event.text),
      ['本机 ', '本机 转写'],
    );
    assert.deepEqual(
      events.values.filter(event => event.kind === 'final').map(event => event.text),
      ['本机 转写'],
    );
    const trailing = Buffer.alloc(800, 0xd5); // Exactly 100 ms of PCMU/8 kHz.
    session.sendAudio(trailing);
    const secondAudio = await peer.frames.wait(
      event => event.type === 'input_audio_buffer.append' && event.audio !== firstAudio.audio,
    );
    assert.deepEqual(Buffer.from(secondAudio.audio, 'base64'), trailing);
    session.close();
    await peer.frames.wait(event => event.type === 'input_audio_buffer.commit');
    await events.wait(event => event.kind === 'final' && event.text === 'Stopped final');
    await peer.closed.wait();
    assert.equal(session.isConnected(), false);
    assert.equal(peer.binaryFrames, 0);
    assert.equal(
      events.values.some(event => event.kind === 'error'),
      false,
    );
    await service.peers.expectNoNewEvent();
    assert.equal(service.peers.values.length, 1);
  } finally {
    session.close();
    await service.close();
  }

  // The native ASR transport supports reconnect; the provider must reset item/delta state.
  const reconnecting = await fakeService(acknowledge);
  const reconnectEvents = channel('reconnected transcription callback');
  const reconnectSession = create(reconnecting, '', reconnectEvents);
  try {
    await reconnectSession.connect();
    const first = await reconnecting.peers.wait();
    assertUpgrade(first, '/deployment/audio/realtime?intent=transcription', '');
    await first.send({
      type: 'conversation.item.input_audio_transcription.delta',
      item_id: 'reused',
      delta: 'Old generation ',
    });
    await reconnectEvents.wait(event => event.kind === 'partial');
    first.socket.terminate();
    const second = await reconnecting.peers.wait(peer => peer !== first);
    await checkUpdate(second);
    await second.send({
      type: 'conversation.item.input_audio_transcription.delta',
      item_id: 'reused',
      delta: 'New generation',
    });
    await second.send({
      type: 'conversation.item.input_audio_transcription.completed',
      item_id: 'reused',
      transcript: 'New generation',
    });
    await reconnectEvents.wait(event => event.kind === 'final');
    assert.deepEqual(
      reconnectEvents.values.filter(event => event.kind === 'partial').map(event => event.text),
      ['Old generation ', 'New generation'],
    );
    assert.deepEqual(
      reconnectEvents.values.filter(event => event.kind === 'final').map(event => event.text),
      ['New generation'],
    );
    assertUpgrade(second, '/deployment/audio/realtime?intent=transcription', '');
    reconnectSession.close();
    second.socket.close(1000, 'done');
    await second.closed.wait();
  } finally {
    reconnectSession.close();
    await reconnecting.close();
  }

  const rejected = await fakeService((peer, frame) => {
    if (frame.type === 'session.update')
      void peer.send({
        type: 'error',
        error: { code: 'invalid_api_key', message: 'Fixture ASR rejected' },
      });
  });
  const failureEvents = channel('failed transcription callback');
  const failed = create(rejected, 'rejected-fixture-key', failureEvents);
  try {
    await assert.rejects(failed.connect(), /Fixture ASR rejected/);
    const peer = await rejected.peers.wait();
    await peer.closed.wait();
    assert.equal(failed.isConnected(), false);
    assert.match(
      (await failureEvents.wait(event => event.kind === 'error')).message,
      /Fixture ASR rejected/,
    );
    assert.equal(rejected.peers.values.length, 1);
  } finally {
    failed.close();
    await rejected.close();
  }
}

