// Expectations here are hand-written service contracts, not generated by production codecs.
function channel(label) {
  const values = [];
  const waiters = new Set();
  return {
    values,
    push(value) {
      assert.ok(values.length < 512, `${label} exceeded its fixture event bound`);
      values.push(value);
      for (const waiter of [...waiters]) if (waiter.predicate(value)) waiter.finish(value);
    },
    wait(predicate = () => true, timeout = 5_000) {
      const present = values.find(predicate);
      if (present !== undefined) return Promise.resolve(present);
      return new Promise((resolve, reject) => {
        const timer = setTimeout(() => {
          waiters.delete(waiter);
          reject(new Error(`Timed out waiting for ${label}`));
        }, timeout);
        const waiter = {
          predicate,
          finish: value => {
            clearTimeout(timer);
            waiters.delete(waiter);
            resolve(value);
          },
        };
        waiters.add(waiter);
      });
    },
    // Absence checks have an explicit event guard, beyond the native first retry delay.
    expectNoNewEvent(timeout = 1_200) {
      return new Promise((resolve, reject) => {
        const timer = setTimeout(() => {
          waiters.delete(waiter);
          resolve();
        }, timeout);
        const waiter = {
          predicate: () => true,
          finish: () => {
            clearTimeout(timer);
            waiters.delete(waiter);
            reject(new Error(`Unexpected additional ${label}`));
          },
        };
        waiters.add(waiter);
      });
    },
  };
}

async function fakeService(onFrame) {
  const peers = channel('WebSocket connection');
  const server = new WebSocketServer({ host: '127.0.0.1', port: 0, maxPayload: 1024 * 1024 });
  await new Promise((resolve, reject) => {
    server.once('listening', resolve);
    server.once('error', reject);
  });
  server.on('connection', (socket, request) => {
    const frames = channel('client wire frame');
    const closed = channel('socket close');
    const peer = {
      socket,
      request,
      frames,
      closed,
      binaryFrames: 0,
      send: event =>
        new Promise((resolve, reject) =>
          socket.send(JSON.stringify(event), error => (error ? reject(error) : resolve())),
        ),
    };
    socket.on('message', (bytes, binary) => {
      if (binary) peer.binaryFrames += 1;
      const event = JSON.parse(bytes.toString());
      frames.push(event);
      onFrame?.(peer, event, peers.values.length);
    });
    socket.on('close', (code, reason) => closed.push({ code, reason: reason.toString() }));
    socket.on('error', () => undefined);
    peers.push(peer);
    void peer.send({ type: 'session.created', session: { id: `fake-${peers.values.length}` } });
  });
  return {
    peers,
    baseUrl: `http://127.0.0.1:${server.address().port}/deployment/audio`,
    async close() {
      for (const socket of server.clients) socket.terminate();
      await new Promise(resolve => server.close(resolve));
    },
  };
}

