export const sidePanelLanguage = navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';

export function sidePanelText(key, values = {}) {
  const template = translations[sidePanelLanguage][key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}

export function sidePanelConnectionError(code) {
  return sidePanelText(
    typeof code === 'string' && /^[A-Z_]+$/.test(code) && Object.hasOwn(translations.en, code)
      ? code
      : 'SOCKET_ERROR',
  );
}

export function localizeSidePanel(document) {
  document.documentElement.lang = sidePanelLanguage === 'zh' ? 'zh-CN' : 'en';
  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = sidePanelText(element.dataset.i18n);
  }
  for (const attribute of ['title', 'aria-label', 'placeholder']) {
    for (const element of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(
        attribute,
        sidePanelText(element.getAttribute(`data-i18n-${attribute}`)),
      );
    }
  }
}
