export type GreetingPeriod = keyof typeof HOME_GREETINGS;

export function getGreetingPeriod(hour: number): GreetingPeriod {
  if (hour < 5 || hour >= 23) return 'Night';
  if (hour < 11) return 'Morning';
  if (hour < 14) return 'Noon';
  if (hour < 18) return 'Afternoon';
  return 'Evening';
}

export function pickHomeGreeting(period: GreetingPeriod, previousKey?: string): string {
  const pool = HOME_GREETINGS[period];
  const alternatives = pool.filter(item => item.key !== previousKey);
  const candidates = alternatives.length ? alternatives : pool;
  return candidates[Math.floor(Math.random() * candidates.length)].key;
}

export function getHomeGreetingTranslations(language: 'zh' | 'en'): Record<string, string> {
  return Object.fromEntries(
    Object.values(HOME_GREETINGS).flatMap(pool => pool.map(item => [item.key, item[language]])),
  );
}
