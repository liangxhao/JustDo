function replaceExactlyOnce(content, original, replacement, description, filePath) {
  const firstIndex = content.indexOf(original);
  if (firstIndex === -1) {
    throw new Error(`OpenClaw ${description} patch target not found: ${filePath}`);
  }
  if (content.indexOf(original, firstIndex + original.length) !== -1) {
    throw new Error(`OpenClaw ${description} patch target is ambiguous: ${filePath}`);
  }
  return content.replace(original, replacement);
}

function patchFile(filePath) {
  let content = fs.readFileSync(filePath, 'utf8');
  const patchMarkers = [
    HELPER_MARKER,
    RENAMED_RESOLVER,
    RESOLVER_WRAPPER,
    COMPACTION_MARKER,
  ];
  const presentMarkerCount = patchMarkers.filter(marker => content.includes(marker)).length;
  if (presentMarkerCount === patchMarkers.length) return false;
  if (presentMarkerCount > 0) {
    throw new Error(
      `OpenClaw LiteLLM session patch found an incomplete or earlier patch revision; regenerate the pristine runtime before patching: ${filePath}`,
    );
  }

  // Patch 1: normal embedded-agent model requests.
  content = replaceExactlyOnce(
    content,
    ORIGINAL_RESOLVER,
    `${HELPER_SOURCE}\n${RENAMED_RESOLVER}`,
    'LiteLLM session resolver',
    filePath,
  );
  content = replaceExactlyOnce(
    content,
    WRAPPER_ANCHOR,
    `${RESOLVER_WRAPPER}\n${WRAPPER_ANCHOR}`,
    'LiteLLM session wrapper',
    filePath,
  );

  // Patch 2: compaction-safeguard's direct, staged generateSummary2() requests.
  content = replaceExactlyOnce(
    content,
    ORIGINAL_SUMMARY_GENERATION,
    PATCHED_SUMMARY_GENERATION,
    'LiteLLM compaction summary generator',
    filePath,
  );
  content = replaceExactlyOnce(
    content,
    ORIGINAL_SUMMARY_CHUNK_CALL,
    PATCHED_SUMMARY_CHUNK_CALL,
    'LiteLLM compaction summary chunk',
    filePath,
  );
  content = replaceExactlyOnce(
    content,
    ORIGINAL_SUMMARIZE_IN_STAGES_FIELDS,
    PATCHED_SUMMARIZE_IN_STAGES_FIELDS,
    'LiteLLM staged compaction summary',
    filePath,
  );
  content = replaceExactlyOnce(
    content,
    ORIGINAL_COMPACTION_RUNTIME_MODEL,
    PATCHED_COMPACTION_RUNTIME_MODEL,
    'LiteLLM compaction runtime session',
    filePath,
  );
  content = replaceExactlyOnce(
    content,
    ORIGINAL_ACTIVE_EXTENSION_FACTORY,
    PATCHED_ACTIVE_EXTENSION_FACTORY,
    'LiteLLM active-session compaction factory',
    filePath,
  );
  content = replaceExactlyOnce(
    content,
    ORIGINAL_COMPACTION_EXTENSION_FACTORY,
    PATCHED_COMPACTION_EXTENSION_FACTORY,
    'LiteLLM standalone compaction factory',
    filePath,
  );
  for (const [original, replacement] of SUMMARIZATION_SESSION_FIELDS) {
    content = replaceExactlyOnce(
      content,
      original,
      replacement,
      'LiteLLM safeguard summarization session',
      filePath,
    );
  }

  fs.writeFileSync(filePath, content, 'utf8');
  return true;
}

function applyPatch(runtimeDir, options = {}) {
  const bundlePath = path.join(runtimeDir, 'gateway-bundle.mjs');
  const label = options.label || 'patch-openclaw-litellm-session-id';
  if (!fs.existsSync(bundlePath)) {
    if (options.verbose) {
      console.log(`[${label}] Gateway bundle not generated yet; deferring session metadata patch.`);
    }
    return [];
  }

  const patched = patchFile(bundlePath) ? ['gateway-bundle.mjs'] : [];
  if (patched.length > 0) {
    console.log(`[${label}] Added LiteLLM-compatible session metadata forwarding.`);
  } else if (options.verbose) {
    console.log(`[${label}] LiteLLM session metadata forwarding already applied.`);
  }
  return patched;
}

