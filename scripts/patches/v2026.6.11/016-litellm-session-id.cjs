// Purpose: Attach the active OpenClaw session id as LiteLLM-compatible
// metadata on every OpenAI-compatible request associated with a session.
//
// This patch covers two independent OpenClaw request paths:
// 1. Rename and wrap resolveEmbeddedAgentStreamFn() so normal agent/model
//    requests add the active session UUID as metadata.session_id.
// 2. Thread the session UUID through compaction-safeguard's staged summary
//    pipeline and provide generateSummary2() with a payload-patching stream.
//    The safeguard calls generateSummary2() directly instead of reusing the
//    agent stream, so it otherwise omits session metadata. This covers manual,
//    threshold, overflow, timeout-recovery, and mid-turn compaction summaries,
//    including every chunk/retry generated by staged summarization.
//
// Existing request metadata is preserved; session_id is replaced with the
// authoritative active OpenClaw session UUID.
//
// Application model: apply both changes atomically to a pristine generated
// bundle. A bundle containing only an earlier revision of this patch is
// rejected instead of being patched incrementally; regenerate the runtime
// (for example with OPENCLAW_FORCE_INSTALL=1) before applying this revision.
// Affected OpenClaw version: v2026.6.11.
// Risk: OpenAI-compatible endpoints receive one additional metadata key.
// Remove when: OpenClaw forwards sessionId as metadata.session_id for OpenAI
// Chat Completions and Responses transports, including safeguard compaction.
// Upstream tracking: TODO(openclaw): request session metadata forwarding.
// Temporary: yes.

