'use strict';

const path = require('path');
const esbuild = require('esbuild');

const repoRoot = path.resolve(__dirname, '../..');

esbuild.buildSync({
  entryPoints: [
    path.join(
      repoRoot,
      'plugins/browser-extensions/browser-assistant/scripts/browser-extension-markdown-entry.mjs',
    ),
  ],
  outfile: path.join(
    repoRoot,
    'plugins',
    'browser-extensions',
    'browser-assistant',
    'conversation-overlay',
    'modules',
    'sidepanel-markdown.js',
  ),
  bundle: true,
  format: 'esm',
  legalComments: 'none',
  minify: true,
  target: ['chrome125'],
  banner: {
    js: '/*! Bundles markdown-it 14.3.0 (MIT): https://github.com/markdown-it/markdown-it */',
  },
});

// Share desktop parsing and cards without the Electron-backed config service.
esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'browser-extension-rich-content.ts')],
  outfile: path.join(
    repoRoot,
    'plugins/browser-extensions/browser-assistant/conversation-overlay/modules/sidepanel-rich-content.js',
  ),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  minify: true,
  tsconfig: path.join(repoRoot, 'tsconfig.json'),
  alias: { '@/services/i18n': path.join(__dirname, 'browser-extension-i18n.ts') },
  target: ['chrome125'],
});
const fs = require('fs');
const chatStyles = fs.readFileSync(
  path.join(repoRoot, 'src/renderer/libs/openclaw-chat/components/justdo-chat.styles.ts'),
  'utf8',
);
const annotationStart = chatStyles.indexOf('    .browser-annotation-message {');
const annotationEnd = chatStyles.indexOf('    .message-attachment-list-item {', annotationStart);
if (annotationStart < 0 || annotationEnd <= annotationStart) {
  throw new Error('Browser annotation styles were not found in the chat style source.');
}
const annotationStyles = chatStyles.slice(annotationStart, annotationEnd);
const presentationStyles = [
  ['    .chat-divider {', '    .chat-group__avatar {'],
  ['    .progress-card-receipt {', '    .timeline-content__body > :first-child {'],
]
  .map(([startSelector, endSelector]) => {
    const start = chatStyles.indexOf(startSelector);
    const end = chatStyles.indexOf(endSelector, start);
    if (start < 0 || end <= start)
      throw new Error(`Desktop chat styles were not found: ${startSelector}`);
    return chatStyles
      .slice(start, end)
      .replaceAll('--justdo-chat-text-secondary', '--chat-muted')
      .replaceAll('--justdo-chat-muted', '--chat-muted')
      .replaceAll('--justdo-chat-border', '--chat-border')
      .replaceAll('--justdo-chat-thinking-bg', '--chat-surface');
  })
  .join('\n');
fs.writeFileSync(
  path.join(
    repoRoot,
    'plugins/browser-extensions/browser-assistant/conversation-overlay/modules/sidepanel-rich-content.css',
  ),
  '/* Generated by build-browser-extension-markdown.cjs. */\n' +
    annotationStyles +
    presentationStyles +
    fs.readFileSync(
      path.join(repoRoot, 'src/renderer/features/browser/recording/browserRecording.css'),
      'utf8',
    ),
);
