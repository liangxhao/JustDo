'use strict';

const path = require('path');
const esbuild = require('esbuild');

const repoRoot = path.resolve(__dirname, '../..');

esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'browser-extension-markdown-entry.mjs')],
  outfile: path.join(
    repoRoot,
    'resources',
    'browser-extension',
    'conversation-overlay',
    'modules',
    'sidepanel-markdown.js',
  ),
  bundle: true,
  format: 'esm',
  legalComments: 'none',
  minify: true,
  target: ['chrome125'],
  banner: {
    js: '/*! Bundles markdown-it 14.3.0 (MIT): https://github.com/markdown-it/markdown-it */',
  },
});

// Share desktop parsing and cards without the Electron-backed config service.
esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'browser-extension-rich-content.ts')],
  outfile: path.join(
    repoRoot,
    'resources/browser-extension/conversation-overlay/modules/sidepanel-rich-content.js',
  ),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  minify: true,
  tsconfig: path.join(repoRoot, 'tsconfig.json'),
  alias: { '@/services/i18n': path.join(__dirname, 'browser-extension-i18n.ts') },
  target: ['chrome125'],
});
const fs = require('fs');
const chatStyles = fs.readFileSync(
  path.join(repoRoot, 'src/renderer/libs/openclaw-chat/components/justdo-chat.ts'),
  'utf8',
);
const annotationStyles = chatStyles.slice(
  chatStyles.indexOf('      .browser-annotation-message {'),
  chatStyles.indexOf('      .message-attachment-list-item {'),
);
fs.writeFileSync(
  path.join(
    repoRoot,
    'resources/browser-extension/conversation-overlay/modules/sidepanel-rich-content.css',
  ),
  '/* Generated by build-browser-extension-markdown.cjs. */\n' +
    annotationStyles +
    fs.readFileSync(
      path.join(repoRoot, 'src/renderer/features/browser/browserRecording.css'),
      'utf8',
    ),
);
