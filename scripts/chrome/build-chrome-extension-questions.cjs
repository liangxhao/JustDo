'use strict';

const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const ts = require('typescript');
const postcss = require('postcss');
const tailwind = require('tailwindcss');

const repoRoot = path.resolve(__dirname, '../..');
const components = path.join(repoRoot, 'src/renderer/features/cowork/components/questions');
const output = path.join(repoRoot, 'plugins/chrome-extensions/chrome-assistant/conversation-overlay/modules');
const temporary = path.join(repoRoot, 'build/chrome-questions');
const componentNames = ['CoworkQuestionWizard.tsx', 'AskUserWaitPolicyNotice.tsx'];

// Only literal strings used by the shared wizard travel to Chrome, without the
// desktop settings service, product metadata, or the application's full dictionary.
function questionTranslations() {
  const keys = new Set(componentNames.flatMap(name =>
    [...fs.readFileSync(path.join(components, name), 'utf8').matchAll(/'(coworkQuestion\w+|coworkCancelRequest|close)'/g)]
      .map(match => match[1])));
  const dictionaries = { zh: {}, en: {} };
  for (const file of ['chatTranslations.ts', 'settingsTranslations.ts']) {
    const filename = path.join(repoRoot, 'src/renderer/services/i18n', file);
    const source = ts.createSourceFile(filename, fs.readFileSync(filename, 'utf8'), ts.ScriptTarget.Latest, true);
    for (const statement of source.statements) {
      if (!ts.isVariableStatement(statement)) continue;
      for (const declaration of statement.declarationList.declarations) {
        if (!declaration.initializer || !ts.isObjectLiteralExpression(declaration.initializer)) continue;
        for (const language of declaration.initializer.properties) {
          const name = language.name?.getText(source);
          if (!(name in dictionaries) || !ts.isPropertyAssignment(language) || !ts.isObjectLiteralExpression(language.initializer)) continue;
          for (const property of language.initializer.properties) {
            const key = property.name?.getText(source).replace(/^['"]|['"]$/g, '');
            if (keys.has(key) && ts.isPropertyAssignment(property) && ts.isStringLiteral(property.initializer))
              dictionaries[name][key] = property.initializer.text;
          }
        }
      }
    }
  }
  for (const language of Object.keys(dictionaries)) {
    for (const key of keys) {
      if (!dictionaries[language][key]) throw new Error(`Missing desktop question translation: ${language}.${key}`);
    }
  }
  return dictionaries;
}

async function main() {
  fs.mkdirSync(temporary, { recursive: true });
  const translationFile = path.join(temporary, 'translations.ts');
  fs.writeFileSync(translationFile,
    `const translations = ${JSON.stringify(questionTranslations())};\n` +
    "const language = navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';\n" +
    'export const i18nService = { t: (key) => translations[language][key] ?? key };\n');
  const result = esbuild.buildSync({
    entryPoints: [path.join(components, 'chromeQuestionPanel.tsx')],
    absWorkingDir: repoRoot,
    outfile: path.join(output, 'sidepanel-questions.js'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['chrome125'],
    tsconfig: path.join(repoRoot, 'tsconfig.json'),
    alias: { '@/services/i18n': translationFile },
    define: { 'process.env.NODE_ENV': '"production"' },
    minify: true,
    legalComments: 'eof',
    write: false,
    banner: { js: '// Generated by scripts/chrome/build-chrome-extension-questions.cjs. Do not edit.' },
  });
  const utilities = await postcss([tailwind({
    presets: [require('../../plugins/sdk/app-plugin-build/theme-preset.cjs')],
    content: componentNames.map(name => path.join(components, name)),
    important: '#questions',
    corePlugins: { preflight: false },
  })]).process('@tailwind utilities;', { from: undefined });
  for (const file of result.outputFiles) {
    if (file.path.endsWith('.js')) fs.writeFileSync(file.path, file.text);
    else if (file.path.endsWith('.css')) {
      const desktopCss = postcss.parse(file.text);
      desktopCss.walkRules(rule => {
        rule.selectors = rule.selectors.map(selector => selector.startsWith('.dark ')
          ? `#questions.dark ${selector.slice(6)}` : `#questions ${selector}`);
      });
      fs.writeFileSync(file.path,
        '/* Generated by scripts/chrome/build-chrome-extension-questions.cjs. Do not edit. */\n' +
        fs.readFileSync(path.join(__dirname, 'chrome-question-panel.css'), 'utf8') + '\n' +
        utilities.css + '\n' + desktopCss.toString());
    }
  }
}

main().catch(error => { process.stderr.write(`${error.stack || error}\n`); process.exitCode = 1; });
